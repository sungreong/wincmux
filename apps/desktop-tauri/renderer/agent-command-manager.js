"use strict";
(() => {
  const settings = document.getElementById("terminalRendererDialog");
  const opener = document.getElementById("agentCommandManagerBtn");
  if (!settings || !opener) return;
  const dialog = document.createElement("dialog");
  dialog.className = "agent-command-manager";
  dialog.setAttribute("aria-labelledby", "agentCommandManagerTitle");
  const header = document.createElement("header");
  const title = document.createElement("h2");
  title.id = "agentCommandManagerTitle";
  title.textContent = "명령·스킬 관리";
  const introduction = document.createElement("p");
  introduction.textContent = "에이전트별 기본 예시와 내 명령을 관리합니다. 목록 밖의 스킬도 입력창에서 실행할 수 있습니다.";
  header.append(title, introduction);
  const label = document.createElement("label");
  label.textContent = "명령 또는 스킬";
  const input = document.createElement("textarea");
  input.rows = 2;
  input.maxLength = 200;
  input.spellcheck = false;
  input.placeholder = "예: /goal 또는 $my-skill";
  label.append(input);
  const commands = window.wincmuxAgentCommandInput.create(input);
  commands.panel.open = true;
  const footer = document.createElement("footer");
  const close = document.createElement("button");
  close.type = "button";
  close.textContent = "닫기";
  close.addEventListener("click", () => dialog.close());
  footer.append(close);
  dialog.append(header, label, commands.panel, footer);
  document.body.append(dialog);
  opener.addEventListener("click", () => {
    settings.close();
    commands.reload();
    void commands.reloadSkills();
    dialog.showModal();
    input.focus();
  });
  window.wincmuxAgentCommandManager = { open: () => opener.click() };
})();
